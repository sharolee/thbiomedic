/** 解析素材 key 为可引用的绝对地址；key 不存在时抛错（构建期即可暴露） */
export function assetUrl(key: string): string {
  const p = ASSET_PATHS[key];
  if (p === undefined) {
    throw new Error('[assets] 未知素材 key: ' + key);
  }
  return p.startsWith('/') ? p : ORIGIN + p;
}

/** 解析本地化例外资产地址 */
export function localAsset(key: LocalAssetKey): string {
  return LOCAL_ASSETS[key];
}
